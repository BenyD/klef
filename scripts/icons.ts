/* Renders the tab icons and the home-screen icon in public/ from the mark
   geometry in src/web/lib/strand.ts: favicon.svg (and its light and dark
   twins, which App.tsx swaps between), plus apple-touch-icon.png at 180 px
   through resvg. Deterministic; rerun with `pnpm icons`. The OG image reads
   the same geometry (`pnpm og`). */

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { Resvg } from "@resvg/resvg-js";
import { STRAND_SMALL, markTileSvg } from "../src/web/lib/strand.ts";

const root = path.resolve(import.meta.dirname, "..");
const pub = (file: string) => path.join(root, "public", file);

// The tab icon is drawn at 16 and 32 px, where the standard strands and
// gap would blur together: bolder bars, a wider gap, a little less padding.
const note =
  "<!-- Klef mark: three strands woven into an asterisk, ink on the ember\n" +
  "     tile, for both colour schemes. Generated by scripts/icons.ts from\n" +
  "     src/web/lib/strand.ts; do not edit by hand. -->\n";
const favicon = note + markTileSvg({ strand: STRAND_SMALL, pad: 14 }) + "\n";
for (const file of ["favicon.svg", "favicon-light.svg", "favicon-dark.svg"]) {
  await writeFile(pub(file), favicon);
  console.log(`wrote public/${file}`);
}

// The home-screen icon is large enough for the standard mark. iOS rounds
// the corners itself, so the tile is a full, opaque square here.
const SIZE = 180;
const png = new Resvg(markTileSvg({ size: SIZE, rx: 0 }), {
  fitTo: { mode: "width", value: SIZE },
}).render();
await writeFile(pub("apple-touch-icon.png"), png.asPng());
console.log(`wrote public/apple-touch-icon.png (${SIZE}x${SIZE})`);
